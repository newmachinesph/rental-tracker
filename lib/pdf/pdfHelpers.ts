import jsPDF from 'jspdf';
import type { OwnerInfo } from '@/lib/types';

// Brand colors (RGB tuples)
export const C = {
  primary: [37, 99, 235] as const,      // #2563eb
  dark: [15, 23, 42] as const,          // #0f172a
  slate700: [51, 65, 85] as const,      // #334155
  slate500: [100, 116, 139] as const,   // #64748b
  slate400: [148, 163, 184] as const,   // #94a3b8
  green: [22, 163, 74] as const,        // #16a34a
  red: [220, 38, 38] as const,          // #dc2626
  amber: [217, 119, 6] as const,        // #d97706
  blue: [37, 99, 235] as const,         // #2563eb
  white: [255, 255, 255] as const,
  lightGray: [248, 250, 252] as const,  // #f8fafc
  border: [226, 232, 240] as const,     // #e2e8f0
  headerBg: [241, 245, 249] as const,   // #f1f5f9
};

const PAGE_W = 210; // A4 width mm
const MARGIN = 15;
const CONTENT_W = PAGE_W - MARGIN * 2;

export function drawLetterhead(doc: jsPDF, owner: OwnerInfo): number {
  // Blue header bar
  doc.setFillColor(...C.primary);
  doc.rect(0, 0, PAGE_W, 22, 'F');

  // Company name in header
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.setTextColor(...C.white);
  doc.text(owner.company || 'Property Management', MARGIN, 14);

  // Owner details below header
  let y = 30;
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.setTextColor(...C.slate500);

  const details: string[] = [];
  if (owner.name) details.push(owner.name);
  if (owner.address) details.push(owner.address);
  const contactParts: string[] = [];
  if (owner.phone) contactParts.push(`Tel: ${owner.phone}`);
  if (owner.email) contactParts.push(owner.email);
  if (contactParts.length) details.push(contactParts.join('  |  '));

  details.forEach((line) => {
    doc.text(line, MARGIN, y);
    y += 4.5;
  });

  // Divider
  y += 2;
  doc.setDrawColor(...C.border);
  doc.setLineWidth(0.3);
  doc.line(MARGIN, y, PAGE_W - MARGIN, y);
  y += 6;

  return y;
}

export function drawFooter(doc: jsPDF): void {
  const pageCount = doc.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    const h = doc.internal.pageSize.getHeight();
    doc.setFont('helvetica', 'italic');
    doc.setFontSize(7.5);
    doc.setTextColor(...C.slate400);
    doc.text(`Page ${i} of ${pageCount}`, MARGIN, h - 8);
    doc.text(
      `Generated by RentalTracker on ${fmtDate(new Date().toISOString())}`,
      PAGE_W - MARGIN,
      h - 8,
      { align: 'right' },
    );
  }
}

export function fmtCurrency(n: number, symbol: string = '₱'): string {
  return `${symbol}${n.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;
}

export function fmtDate(d: string): string {
  if (!d) return '-';
  return new Date(d).toLocaleDateString('en-US', {
    year: 'numeric',
    month: 'short',
    day: 'numeric',
  });
}

export function checkPageBreak(doc: jsPDF, y: number, needed: number = 30): number {
  const h = doc.internal.pageSize.getHeight();
  if (y + needed > h - 20) {
    doc.addPage();
    return 20;
  }
  return y;
}

export function drawTitle(doc: jsPDF, title: string, y: number): number {
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.setTextColor(...C.dark);
  doc.text(title, PAGE_W / 2, y, { align: 'center' });
  return y + 10;
}

export function drawInfoBlock(
  doc: jsPDF,
  leftLines: [string, string][],
  rightLines: [string, string][],
  y: number,
): number {
  doc.setFontSize(9);
  const leftX = MARGIN;
  const rightX = PAGE_W / 2 + 10;
  const maxLines = Math.max(leftLines.length, rightLines.length);

  for (let i = 0; i < maxLines; i++) {
    if (leftLines[i]) {
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...C.slate500);
      doc.text(leftLines[i][0], leftX, y);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...C.dark);
      doc.text(leftLines[i][1], leftX + 40, y);
    }
    if (rightLines[i]) {
      doc.setFont('helvetica', 'bold');
      doc.setTextColor(...C.slate500);
      doc.text(rightLines[i][0], rightX, y);
      doc.setFont('helvetica', 'normal');
      doc.setTextColor(...C.dark);
      doc.text(rightLines[i][1], rightX + 40, y);
    }
    y += 5.5;
  }

  return y + 4;
}

export function drawSummaryBoxes(
  doc: jsPDF,
  boxes: { label: string; value: string; color?: readonly [number, number, number] }[],
  y: number,
): number {
  const boxW = CONTENT_W / boxes.length;
  const boxH = 18;

  boxes.forEach((box, i) => {
    const x = MARGIN + i * boxW;
    doc.setFillColor(...C.lightGray);
    doc.setDrawColor(...C.border);
    doc.roundedRect(x + 1, y, boxW - 2, boxH, 2, 2, 'FD');

    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.setTextColor(...C.slate500);
    doc.text(box.label, x + boxW / 2, y + 6, { align: 'center' });

    doc.setFont('helvetica', 'bold');
    doc.setFontSize(11);
    doc.setTextColor(...(box.color || C.dark));
    doc.text(box.value, x + boxW / 2, y + 14, { align: 'center' });
  });

  return y + boxH + 8;
}

export { MARGIN, CONTENT_W, PAGE_W };
